int _write(int fd, unsigned char *buf, int len) {
  if (fd == 1 || fd == 2) {
    HAL_UART_Transmit(&huart3, buf, len, 999);
  }
  return len;
}

uint64_t mg_millis(void) {
  return HAL_GetTick();
}

bool mg_random(void *buf, size_t len) {
  for (size_t n = 0; n < len; n += sizeof(uint32_t)) {
    uint32_t r;
    HAL_RNG_GenerateRandomNumber(&hrng, &r);
    memcpy((char *) buf + n, &r, n + sizeof(r) > len ? len - n : sizeof(r));
  }
  return true;
}

static void ev_handler(struct mg_connection *c, int ev, void *ev_data) {
  if (ev == MG_EV_ACCEPT) {
    MG_INFO(("Client connected: %M", mg_print_ip_port, &c->rem));
  } else if (ev == MG_EV_CLOSE) {
    MG_INFO(("Client disconnected"));
  } else if (ev == MG_EV_ERROR) {
    MG_ERROR(("Error: %s", (char *) ev_data));
  }
}

static void run_mongoose(void) {
  struct mg_mgr mgr;
  mg_mgr_init(&mgr);
  mg_log_set(MG_LL_DEBUG);

  struct mg_tcpip_driver_stm32h_data driver_data = {.mdc_cr = 4};
  memset(&s_ifp, 0, sizeof(s_ifp));
  s_ifp.mac[0] = 0x02; s_ifp.mac[1] = 0x00; s_ifp.mac[2] = 0x01;
  s_ifp.mac[3] = 0x02; s_ifp.mac[4] = 0x03; s_ifp.mac[5] = 0x06;
  s_ifp.ip   = mg_htonl(MG_U32(192, 168, 0, 11));
  s_ifp.mask = mg_htonl(MG_U32(255, 255, 255, 0));
  s_ifp.gw   = mg_htonl(MG_U32(192, 168, 0, 1));
  s_ifp.driver = &mg_tcpip_driver_stm32h;
  s_ifp.driver_data = &driver_data;

  mg_tcpip_init(&mgr, &s_ifp);

  MG_INFO(("Waiting for network link..."));
  while (s_ifp.state != MG_TCPIP_STATE_READY) {
    mg_mgr_poll(&mgr, 0);
  }
  MG_INFO(("Network Ready! IP: %M", mg_print_ip4, &s_ifp.ip));

  mg_listen(&mgr, "tcp://0.0.0.0:1234", ev_handler, NULL);
  MG_INFO(("Listening on port 1234..."));

  for (;;) {
    mg_mgr_poll(&mgr, 0);
  }
}

